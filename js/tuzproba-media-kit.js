const locales = { en: "en-US", hu: "hu-HU", de: "de-DE" };
const validLanguages = new Set(Object.keys(translations));
let currentLang = "en";
let currentData = fallbackData;
let renderedVideoIds = [];

function t(path) {
  return path.split(".").reduce((value, key) => value?.[key], translations[currentLang]) ?? path;
}

function text(id, value) {
  const el = document.getElementById(id);
  if (el) el.textContent = value;
}

function localNumber(value, maximumFractionDigits = 1, minimumFractionDigits = 0) {
  return new Intl.NumberFormat(locales[currentLang], { maximumFractionDigits, minimumFractionDigits }).format(Number(value) || 0);
}

function compactNumber(value) {
  const number = Number(value) || 0;
  const absolute = Math.abs(number);
  if (absolute >= 1000000) {
    const scaled = number / 1000000;
    const digits = Math.abs(scaled) >= 100 ? 0 : Math.abs(scaled) >= 10 ? 1 : 2;
    return `${localNumber(scaled, digits)}M`;
  }
  if (absolute >= 1000) {
    const scaled = number / 1000;
    const digits = Math.abs(scaled) >= 100 ? 0 : Math.abs(scaled) >= 10 ? 1 : 2;
    return `${localNumber(scaled, digits)}K`;
  }
  return new Intl.NumberFormat(locales[currentLang]).format(number);
}

function prettyDate(value) {
  try {
    return new Intl.DateTimeFormat(locales[currentLang], { year: "numeric", month: "long", day: "numeric" }).format(new Date(`${value}T12:00:00Z`));
  } catch {
    return value;
  }
}

const countryAliases = {
  hungary: "hungary", "magyarország": "hungary", ungarn: "hungary",
  romania: "romania", "románia": "romania", "rumänien": "romania",
  ukraine: "ukraine", "ukrajna": "ukraine",
  slovakia: "slovakia", "szlovákia": "slovakia", slowakei: "slovakia"
};

const countryNames = {
  hungary: { en: "Hungary", hu: "Magyarország", de: "Ungarn" },
  romania: { en: "Romania", hu: "Románia", de: "Rumänien" },
  ukraine: { en: "Ukraine", hu: "Ukrajna", de: "Ukraine" },
  slovakia: { en: "Slovakia", hu: "Szlovákia", de: "Slowakei" }
};

function translatedCountry(name) {
  const key = countryAliases[String(name || "").trim().toLocaleLowerCase("hu-HU")];
  return key ? countryNames[key][currentLang] : name;
}

function applyStaticTranslations() {
  document.documentElement.lang = currentLang;
  document.title = t("meta.title");
  const metaDescription = document.getElementById("meta-description");
  const ogDescription = document.getElementById("og-description");
  if (metaDescription) metaDescription.content = t("meta.description");
  if (ogDescription) ogDescription.content = t("meta.description");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === currentLang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function renderStats(data) {
  const s = data.stats;
  text("stat-subscribers", `${compactNumber(s.subscribers)}+`);
  text("stat-views28", compactNumber(s.views28d));
  text("stat-views90", compactNumber(s.views90d));
  text("stat-watch90", `${compactNumber(s.watchHours90d)} ${t("stats.hours")}`);
  text("stat-impressions90", compactNumber(s.impressions90d));
  text("stat-ctr", `${localNumber(s.ctr, 2, 2)}%`);
  text("stat-avd", s.avgViewDuration);
  text("stat-growth", `${s.subscriberGrowth90d >= 0 ? "+" : ""}${compactNumber(s.subscriberGrowth90d)}`);
  text("updated-at", prettyDate(data.updatedAt));
}

function renderAudience(data) {
  const a = data.audience;
  text("core-age-label", a.coreAgeLabel);
  text("core-age-share", `${localNumber(a.coreAgeShare, 1, 1)}%`);
  const coreMeter = document.getElementById("core-age-meter");
  if (coreMeter) coreMeter.style.setProperty("--value", `${Math.max(0, Math.min(100, Number(a.coreAgeShare)))}%`);

  text("male-share", `${localNumber(a.male, 1, 1)}%`);
  text("female-share", `${localNumber(a.female, 1, 1)}%`);

  const list = document.getElementById("country-list");
  if (!list) return;
  list.innerHTML = "";
  for (const country of a.countries || []) {
    const row = document.createElement("div");
    row.className = "tp-country-row";
    const safeShare = Math.max(0, Math.min(100, Number(country.share) || 0));
    row.innerHTML = `
      <span class="tp-country-name"></span>
      <span class="tp-country-bar"><span style="width:${safeShare}%"></span></span>
      <span class="tp-country-share">${localNumber(safeShare, 1, 1)}%</span>`;
    row.querySelector(".tp-country-name").textContent = translatedCountry(country.name);
    list.appendChild(row);
  }
}

function renderContact(data) {
  const email = data.contact?.email || fallbackData.contact.email;
  const channel = data.contact?.channelUrl || fallbackData.contact.channelUrl;
  const emailLink = document.getElementById("contact-email");
  const channelLink = document.getElementById("contact-channel");
  if (emailLink) {
    emailLink.href = `mailto:${email}`;
    emailLink.textContent = t("cta.email");
  }
  if (channelLink) {
    channelLink.href = channel;
    channelLink.textContent = t("cta.youtube");
  }
}

function videoEmbed(videoId) {
  const wrap = document.createElement("div");
  wrap.className = "tp-video";
  const iframe = document.createElement("iframe");
  iframe.src = `https://www.youtube-nocookie.com/embed/${encodeURIComponent(videoId)}`;
  iframe.title = t("content.videoTitle");
  iframe.loading = "lazy";
  iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
  iframe.referrerPolicy = "strict-origin-when-cross-origin";
  iframe.allowFullscreen = true;
  wrap.appendChild(iframe);
  return wrap;
}

async function loadRecentVideoIds() {
  try {
    const response = await fetch("/api/youtube?type=recent&channel=tuzproba", { headers: { Accept: "application/json" } });
    if (!response.ok) return [];
    const payload = await response.json();
    return (payload.items || []).map((item) => item.id).filter(Boolean).slice(0, 3);
  } catch {
    return [];
  }
}

function paintVideos(ids) {
  const grid = document.getElementById("video-grid");
  if (!grid) return;
  grid.innerHTML = "";
  if (!ids.length) {
    const empty = document.createElement("div");
    empty.className = "tp-video tp-video-empty";
    empty.textContent = t("content.empty");
    grid.appendChild(empty);
    return;
  }
  ids.forEach((id) => grid.appendChild(videoEmbed(id)));
}

async function renderVideos(data) {
  let ids = Array.isArray(data.featuredVideoIds) ? data.featuredVideoIds.filter(Boolean).slice(0, 3) : [];
  if (!ids.length) ids = await loadRecentVideoIds();
  renderedVideoIds = ids;
  paintVideos(ids);
}

function refreshDynamicLanguage() {
  renderStats(currentData);
  renderAudience(currentData);
  renderContact(currentData);
  paintVideos(renderedVideoIds);
}

function setLanguage(lang, { persist = true, updateUrl = true } = {}) {
  currentLang = validLanguages.has(lang) ? lang : "en";
  if (persist) {
    try { localStorage.setItem("tp_media_lang", currentLang); } catch {}
  }
  if (updateUrl) {
    try {
      const url = new URL(window.location.href);
      url.searchParams.set("lang", currentLang);
      history.replaceState(null, "", url);
    } catch {}
  }
  applyStaticTranslations();
  refreshDynamicLanguage();
}

function resolveInitialLanguage() {
  try {
    const fromUrl = new URL(window.location.href).searchParams.get("lang");
    if (validLanguages.has(fromUrl)) return fromUrl;
  } catch {}
  try {
    const saved = localStorage.getItem("tp_media_lang");
    if (validLanguages.has(saved)) return saved;
  } catch {}
  return "en";
}

async function loadData() {
  try {
    const response = await fetch("/api/tuzproba-media-kit", { headers: { Accept: "application/json" } });
    if (!response.ok) throw new Error("API unavailable");
    const payload = await response.json();
    return payload.data || fallbackData;
  } catch {
    return fallbackData;
  }
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

(async function init() {
  currentLang = resolveInitialLanguage();
  applyStaticTranslations();
  currentData = await loadData();
  renderStats(currentData);
  renderAudience(currentData);
  renderContact(currentData);
  await renderVideos(currentData);
})();
